"""PR body shape predicate: the one-paragraph PR description, checked.

``change-control-policy.md`` § PR body requirements (nous-ergon-ops,
alpha-engine-config-I12733, Brian 2026-10-27) defines the body of every
agent-authored pull request:

    <the harness attribution lines>

    <ONE paragraph, at most 120 words>

    Tracker: alpha-engine-config-I<N>
    Deploy-mechanism: <workflow> | N/A
    Merge: auto | Brian, red line <N> (<which>) · Operator: none | ...

    ---
    _Generated by [Claude Code](<session link>)_

with no headings, tables, bullet lists or retold diff. Templates alone do not
hold a shape: before this rule, 13 templates had drifted into 13 different
section sets, two still asked for a model name the policy had banned, and
bodies ran 400 to 900 words. This module is the deterministic half of the
rule, so a sweep or a CI job can say exactly what is wrong with a body.

Scope, deliberately narrow:

* **Agent-authored bodies only.** A body is agent-authored when it carries
  the harness attribution marker or the Claude Code footer. Fleet agent PRs
  open under a human account, so the author login cannot tell them apart.
  Human-authored bodies pass; the policy lets them carry the elements in any
  form.
* **Bots pass.** Dependabot and scanner bodies are exempt by policy, and
  machine-built bodies (batchers, sweeps) are authored by bot accounts.
* **Decision Queue bodies pass the heading rule.** Their ``## Ask`` /
  ``## Recommendation`` structure is the one permitted exception.
* **The word limit is 150, not 120.** The policy says 120, and this checks
  at 150 so it stays a backstop for the shape rather than a word-counting
  nag. Reviewers hold the 120.

What it can NOT see, and does not pretend to: whether the proof sentence's
command actually ran before the PR opened. That half stays review-enforced.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field

#: The paragraph limit this check enforces. The policy's target is 120.
MAX_PROSE_WORDS = 150

#: Keys that must each start a line. Machine readers anchor on line start
#: (cross_repo_close_reconciliation.py, deploy_release_standard_sweep.py).
REQUIRED_KEYS: tuple[str, ...] = ("Tracker", "Deploy-mechanism", "Merge")

#: Any key line, required or optional. Such lines are not prose.
_KEY_LINE = re.compile(
    r"^\s*(tracker|closes|refs|deploy[ -]mechanism|merge|depends[ -]on|blocked[ -]by|"
    r"verified[ -]when|money[ -]path|monthly cost delta|rollback|first watch)\s*:",
    re.IGNORECASE,
)

_AGENT_MARKERS: tuple[str, ...] = (
    "claude-projects-attribution",
    "_Generated by [Claude Code]",
    "Generated with [Claude Code]",
)

_BOT_LOGINS = re.compile(r"(\[bot\]$|^dependabot|^github-actions|^renovate)", re.IGNORECASE)

_DECISION_QUEUE_HEADINGS = re.compile(r"^##\s+(ask|recommendation|sota|delta)\b", re.IGNORECASE | re.MULTILINE)

_HTML_COMMENT = re.compile(r"<!--.*?-->", re.DOTALL)
_CODE_FENCE = re.compile(r"^```.*?^```[^\n]*$", re.DOTALL | re.MULTILINE)
_HEADING = re.compile(r"^\s{0,3}#{1,6}\s+\S", re.MULTILINE)
_TABLE_RULE = re.compile(r"^\s*\|?\s*:?-{3,}:?\s*(\|\s*:?-{3,}:?\s*)+\|?\s*$", re.MULTILINE)
_MODEL_ID = re.compile(r"\bclaude-(opus|sonnet|haiku|fable)-\d", re.IGNORECASE)

#: Lines that are attribution or footer furniture, not prose.
_FURNITURE = re.compile(
    r"^\s*(_requested by\b|_generated by\b|🤖 generated with\b|---+\s*$|"
    r"https://claude\.ai/code/session_\S+\s*$|\*\*prepared by:\*\*|prepared by:)",
    re.IGNORECASE,
)


@dataclass
class ShapeResult:
    """The verdict on one body: ``ok``, the problems found, and why it was
    in or out of scope."""

    ok: bool
    scope: str
    problems: list[str] = field(default_factory=list)
    prose_words: int = 0


def is_agent_authored(body: str) -> bool:
    """True when the body carries the harness marker or the Claude Code footer."""
    return any(marker in (body or "") for marker in _AGENT_MARKERS)


def _strip_non_prose(body: str) -> str:
    """Remove HTML comments and code fences: neither is rendered prose."""
    return _CODE_FENCE.sub("", _HTML_COMMENT.sub("", body or ""))


def prose_word_count(body: str) -> int:
    """Words of prose in ``body``: everything except comments, code fences,
    key lines, list items, attribution and footer lines."""
    words = 0
    for line in _strip_non_prose(body).splitlines():
        stripped = line.strip()
        if not stripped:
            continue
        if _KEY_LINE.match(stripped) or _FURNITURE.match(stripped):
            continue
        if re.match(r"^([-*+]|\d+\.)\s", stripped):
            continue
        words += len(stripped.split())
    return words


def check_body(body: str, author_login: str = "", author_type: str = "") -> ShapeResult:
    """Check one PR body against the policy shape.

    Never raises on content: every problem is a string in ``problems``, so
    the caller decides whether to fail, comment or only report.
    """
    if author_type.lower() == "bot" or (author_login and _BOT_LOGINS.search(author_login)):
        return ShapeResult(True, "bot author, exempt by policy")
    if not is_agent_authored(body):
        return ShapeResult(True, "human-authored body, elements may take any form")

    problems: list[str] = []
    text = _strip_non_prose(body)

    for key in REQUIRED_KEYS:
        pattern = re.compile(rf"^\s*{key.replace('-', '[ -]')}\s*:", re.IGNORECASE | re.MULTILINE)
        if not pattern.search(text):
            problems.append(f"no line starting `{key}:` (each machine-read key starts its own line)")

    decision_queue = bool(_DECISION_QUEUE_HEADINGS.search(text))
    if not decision_queue and _HEADING.search(text):
        problems.append("contains a markdown heading; the body is one paragraph plus field lines")
    if _TABLE_RULE.search(text):
        problems.append("contains a table; state each fact once in the paragraph")
    if _MODEL_ID.search(text):
        problems.append("names a model identifier; attribution is the session link only")

    words = prose_word_count(body)
    if not decision_queue and words > MAX_PROSE_WORDS:
        problems.append(f"{words} words of prose; the paragraph is at most 120 (checked at {MAX_PROSE_WORDS})")

    scope = "decision-queue body" if decision_queue else "agent-authored body"
    return ShapeResult(not problems, scope, problems, words)


def explain(result: ShapeResult) -> str:
    """One human line per problem, prefixed with where the rule lives."""
    if result.ok:
        return f"PR body shape OK ({result.scope}, {result.prose_words} prose words)."
    lines = ["PR body does not follow change-control-policy.md § PR body requirements:"]
    lines += [f"- {p}" for p in result.problems]
    return "\n".join(lines)
