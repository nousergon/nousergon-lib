"""Tests for nousergon_lib.pr_body_shape (alpha-engine-config-I12733)."""

from __future__ import annotations

from nousergon_lib.pr_body_shape import check_body, explain, prose_word_count

ATTR = (
    '<!-- claude-projects-attribution: {"github_login":"cipher813"} -->\n'
    "_Requested by **Brian** · [project thread](https://claude.ai/code/project/x?thread=y)_\n\n"
)
FOOTER = "\n---\n_Generated by [Claude Code](https://claude.ai/code/session_abc)_\n"
FIELDS = "Tracker: alpha-engine-config-I12733\nDeploy-mechanism: N/A\nMerge: auto · Operator: none\n"
PARA = (
    "Adds five switches so the template deploys into staging without paging. "
    "It closes four of six gaps on aec#12505. Verified: 9836 tests pass. "
    "Merging applies three parameters at defaults.\n\n"
)


def good() -> str:
    return ATTR + PARA + FIELDS + FOOTER


def test_conforming_body_passes():
    r = check_body(good())
    assert r.ok, r.problems
    assert r.prose_words == len(PARA.split())


def test_missing_each_required_key_is_named():
    for key in ("Tracker:", "Deploy-mechanism:", "Merge:"):
        body = good().replace(key, "Xx:")
        r = check_body(body)
        assert not r.ok
        assert any(f"`{key}`" in p for p in r.problems), r.problems


def test_deploy_mechanism_inline_on_merge_line_is_not_enough():
    body = ATTR + PARA + "Tracker: alpha-engine-config-I1\nMerge: auto · Deploy-mechanism: N/A\n" + FOOTER
    r = check_body(body)
    assert any("Deploy-mechanism" in p for p in r.problems)


def test_heading_and_table_fail():
    r = check_body(good().replace(PARA, "## What\n\n| a | b |\n|---|---|\n| 1 | 2 |\n\n" + PARA))
    assert any("heading" in p for p in r.problems)
    assert any("table" in p for p in r.problems)


def test_long_prose_fails_and_reports_count():
    r = check_body(good().replace(PARA, ("word " * 160) + "\n\n"))
    assert not r.ok
    assert any("160 words" in p for p in r.problems)


def test_comments_code_fences_lists_and_keys_are_not_prose():
    extra = "<!-- " + "hidden " * 200 + "-->\n```\n" + "code " * 200 + "\n```\n- item one two three\n"
    assert prose_word_count(good() + extra) == len(PARA.split())


def test_model_identifier_fails():
    r = check_body(good().replace("Verified:", "Prepared by claude-opus-5 and verified:"))
    assert any("model identifier" in p for p in r.problems)


def test_human_and_bot_bodies_are_out_of_scope():
    assert check_body("## Summary\nlong human body " * 50).ok
    assert check_body(good().replace(FIELDS, ""), author_login="dependabot[bot]").ok
    assert check_body(good().replace(FIELDS, ""), author_type="Bot").ok


def test_decision_queue_structure_is_allowed():
    body = ATTR + "## Ask\nPick one.\n\n## Recommendation\nOption A.\n\n" + FIELDS + FOOTER
    assert check_body(body).ok


def test_explain_names_the_policy():
    assert "§ PR body requirements" in explain(check_body(good().replace(FIELDS, "")))
    assert explain(check_body(good())).startswith("PR body shape OK")
